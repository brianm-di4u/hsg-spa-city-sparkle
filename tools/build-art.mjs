#!/usr/bin/env node
// Art pipeline: art-src/sprites/*.png (Blender renders, art-src/blender/pieces.py) and art-src/paint/*.png
// (Codex paintings, see art-src/PROMPTS.md) → WebP via the shared packer (shared/test-harness/art-pack.mjs,
// Chromium, no image libraries) → classic-script packs in assets/ that carry the images as data URIs
// (WebGL refuses file:// images; LESSONS "Visual campaigns"), loaded on demand:
//   art-core.js  board sprites, title, guide, lore frame, postcards        (at boot)
//   art-map.js   the six world-map panels                                  (when the map opens)
//   art-w<n>.js  world n's backdrops, portrait and landscape                (when a level of world n starts)
// Packed WebP files live in art-src/packed/ (committed) so a build without the raw PNGs reuses them.
// Writes src/js/art-list.js so the game only requests packs that exist.
//   node tools/build-art.mjs [--no-pack]
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const game = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(game, 'art-src'), assets = path.join(game, 'assets'), packed = path.join(src, 'packed');
const list = (d) => (fs.existsSync(d) ? fs.readdirSync(d).filter((f) => f.endsWith('.png')).map((f) => f.slice(0, -4)) : []);
const sprites = list(path.join(src, 'sprites')), paints = list(path.join(src, 'paint'));
// sizes are what the screen shows at 2× on a phone, not the generated size
const paintSpec = (n) => {
  // the 2026-11 repainted backdrops are busier, so they pack at 0.6 to stay inside the 6 MB asset budget
  if (/^bg/.test(n) || /^title/.test(n)) return n.endsWith('-l') ? [1280, 853, 0.6] : [768, 1152, 0.6];
  if (/^map/.test(n)) return [640, 960, 0.62];
  if (/^postcard/.test(n)) return [720, 480, 0.66];
  if (/^della/.test(n)) return [360, 540, 0.8];
  return [560, 560, 0.7];
};
const items = [
  ...sprites.map((n) => ({ name: n, src: `sprites/${n}.png`, w: 192, h: 192, fit: 'contain', quality: 0.86 })),
  ...paints.map((n) => {
    const [w, h, quality] = paintSpec(n);
    const it = { name: n, src: `paint/${n}.png`, w, h, fit: /^della/.test(n) ? 'contain' : 'cover', quality };
    if (/^della/.test(n)) it.keyWhite = 6; // generated on flat white; a low tolerance keeps the white uniform
    return it;
  }),
];
if (items.length && !process.argv.includes('--no-pack')) {
  fs.writeFileSync(path.join(src, 'art.json'), JSON.stringify({ quality: 0.8, items }, null, 1) + '\n');
  const packer = [path.join(game, '..', '..', 'shared', 'test-harness', 'art-pack.mjs'), path.join(game, 'shared', 'test-harness', 'art-pack.mjs')].find((p) => fs.existsSync(p));
  execFileSync(process.execPath, [packer, game], { stdio: 'inherit' });
  // the packer writes into assets/; keep the WebP files as build inputs instead of shipping them twice
  fs.mkdirSync(packed, { recursive: true });
  for (const f of fs.readdirSync(assets)) if (f.endsWith('.webp') || f === 'manifest.json') fs.renameSync(path.join(assets, f), path.join(packed, f));
}
const names = fs.existsSync(packed) ? fs.readdirSync(packed).filter((f) => f.endsWith('.webp')).map((f) => f.slice(0, -5)).sort() : [];
if (!names.length) { console.log('art: none packed, vector art only'); process.exit(0); }
const packOf = (n) => (/^bg(\d)/.test(n) ? `w${n[2]}` : /^map/.test(n) ? 'map' : 'core');
const isPaint = (n) => /^(bg|title|map|postcard|della|card)/.test(n);
const packs = {};
for (const n of names) {
  const p = (packs[packOf(n)] ||= { textures: {}, paintings: {} });
  const uri = 'data:image/webp;base64,' + fs.readFileSync(path.join(packed, `${n}.webp`)).toString('base64');
  (isPaint(n) ? p.paintings : p.textures)[n] = uri;
}
for (const f of fs.readdirSync(assets)) if (/^art-.*\.js$/.test(f)) fs.unlinkSync(path.join(assets, f));
const list2 = {};
let total = 0;
for (const [key, p] of Object.entries(packs)) {
  const body = `/* Generated by tools/build-art.mjs: Blender renders and AI-assisted paintings for Spa City Sparkle (art-src/PROMPTS.md). */\n(window.SCS_ART=window.SCS_ART||{})[${JSON.stringify(key)}]=${JSON.stringify(p)};\n`;
  const file = `assets/art-${key}.js`;
  fs.writeFileSync(path.join(game, file), body);
  total += body.length;
  list2[key] = { file, v: crypto.createHash('sha1').update(body).digest('hex').slice(0, 10), textures: Object.keys(p.textures), paintings: Object.keys(p.paintings), kb: Math.round(body.length / 1024) };
}
fs.writeFileSync(path.join(game, 'src', 'js', 'art-list.js'), `// Generated by tools/build-art.mjs: which art packs exist, so the game never requests a missing file\n// (a 404 is a console error and fails the harness).\nexport const ART = ${JSON.stringify({ packs: list2 })};\n`);
console.log(`art: ${Object.entries(list2).map(([k, v]) => `${k} ${v.kb} KB`).join(', ')}; total ${(total / 1024 / 1024).toFixed(2)} MB`);
