#!/usr/bin/env node
// Inlines the OFL fonts (npm @fontsource, installed in tools/dev) into src/styles/fonts.css as data URIs,
// which the build inlines into index.html. Chrome blocks @font-face files on file://, so fonts travel
// inside the stylesheet (property-game pattern). The generated CSS is committed, so a standalone build
// doesn't need tools/dev. node tools/build-fonts.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const GAME = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const NM = path.join(GAME, 'tools', 'dev', 'node_modules', '@fontsource');
const FACES = [
  // titles, level names, callouts: deco-flavoured display face
  ['Righteous', 400, 'righteous/files/righteous-latin-400-normal.woff2'],
  // UI and body text
  ['Nunito', 600, 'nunito/files/nunito-latin-600-normal.woff2'],
  ['Nunito', 800, 'nunito/files/nunito-latin-800-normal.woff2'],
];
const out = path.join(GAME, 'src', 'styles', 'fonts.css');
if (!fs.existsSync(NM)) { if (fs.existsSync(out)) { console.log('fonts: keeping committed fonts.css'); process.exit(0); } throw new Error('install tools/dev first'); }
let css = '/* Generated by tools/build-fonts.mjs from npm @fontsource (SIL Open Font License 1.1). Do not edit. */\n';
for (const [family, weight, file] of FACES) {
  const b64 = fs.readFileSync(path.join(NM, file)).toString('base64');
  css += `@font-face{font-family:"${family}";font-style:normal;font-weight:${weight};font-display:block;src:url(data:font/woff2;base64,${b64}) format("woff2")}\n`;
}
fs.writeFileSync(out, css);
console.log('fonts: src/styles/fonts.css', (css.length / 1024).toFixed(1), 'KB');
